static bool valid_type(McContentRegistryType type){
    return type >= MC_REGISTRY_ITEM && type < MC_REGISTRY_TYPE_COUNT;
}

static size_t compiled_count(McContentRegistryType type){
    switch(type){
        case MC_REGISTRY_ITEM: return MC_CONTENT_REGISTRY_ITEM_COUNT;
        case MC_REGISTRY_BLOCK: return MC_CONTENT_REGISTRY_BLOCK_COUNT;
        case MC_REGISTRY_LIQUID: return MC_CONTENT_REGISTRY_LIQUID_COUNT;
        case MC_REGISTRY_STATUS: return MC_CONTENT_REGISTRY_STATUS_COUNT;
        case MC_REGISTRY_UNIT: return MC_CONTENT_REGISTRY_UNIT_COUNT;
        case MC_REGISTRY_BULLET: return MC_CONTENT_REGISTRY_BULLET_COUNT;
        case MC_REGISTRY_WEATHER: return MC_CONTENT_REGISTRY_WEATHER_COUNT;
        case MC_REGISTRY_PLANET: return MC_CONTENT_REGISTRY_PLANET_COUNT;
        case MC_REGISTRY_SECTOR: return MC_CONTENT_REGISTRY_SECTOR_COUNT;
        case MC_REGISTRY_TEAM: return MC_CONTENT_REGISTRY_TEAM_COUNT;
        default: return 0;
    }
}

static size_t first_index(McContentRegistryType type){
    size_t index = 0;
    for(int current = MC_REGISTRY_ITEM; current < (int)type; current++) index += compiled_count((McContentRegistryType)current);
    return index;
}

McContentRegistryView mc_content_registry_view(void){
    McContentRegistryValidation validation;
    McStatus status = mc_content_registry_validate(&validation);
    return (McContentRegistryView){registry_entries, MC_CONTENT_REGISTRY_TOTAL_COUNT, MC_CONTENT_REGISTRY_VERSION, status == MC_OK};
}

const McContentEntry *mc_content_registry_entries(size_t *count){
    if(count != NULL) *count = MC_CONTENT_REGISTRY_TOTAL_COUNT;
    return registry_entries;
}

size_t mc_content_registry_count(McContentRegistryType type){
    return valid_type(type) ? compiled_count(type) : 0;
}

const McContentEntry *mc_content_registry_find(McContentRegistryType type, const char *name){
    if(!valid_type(type) || name == NULL) return NULL;
    size_t start = first_index(type);
    size_t count = compiled_count(type);
    for(size_t i = 0; i < count; i++) if(strcmp(registry_entries[start + i].name, name) == 0) return &registry_entries[start + i];
    return NULL;
}

const McContentEntry *mc_content_registry_find_id(McContentRegistryType type, uint16_t id){
    if(!valid_type(type)) return NULL;
    size_t start = first_index(type);
    size_t count = compiled_count(type);
    for(size_t i = 0; i < count; i++) if(registry_entries[start + i].id == id) return &registry_entries[start + i];
    return NULL;
}

const McContentEntry *mc_content_registry_at(McContentRegistryType type, size_t ordinal){
    if(!valid_type(type) || ordinal >= compiled_count(type)) return NULL;
    return &registry_entries[first_index(type) + ordinal];
}

const char *mc_content_registry_type_name(McContentRegistryType type){
    static const char *names[MC_REGISTRY_TYPE_COUNT] = {"item", "block", "liquid", "status", "unit", "bullet", "weather", "planet", "sector", "team"};
    return valid_type(type) ? names[type] : "unknown";
}

const char *mc_content_registry_name(McContentRegistryType type, uint16_t id){
    const McContentEntry *entry = mc_content_registry_find_id(type, id);
    return entry == NULL ? NULL : entry->name;
}

int32_t mc_content_registry_legacy_id(McContentRegistryType type, const char *name){
    const McContentEntry *entry = mc_content_registry_find(type, name);
    return entry == NULL ? -1 : entry->legacy_id;
}

const McContentEntry *mc_content_registry_find_legacy_id(McContentRegistryType type, int32_t legacy_id){
    if(!valid_type(type) || legacy_id < 0) return NULL;
    size_t start = first_index(type), count = compiled_count(type);
    for(size_t i = 0; i < count; i++){
        const McContentEntry *entry = &registry_entries[start + i];
        if(entry->legacy_id == legacy_id) return entry;
    }
    return NULL;
}

bool mc_content_registry_has_flag(const McContentEntry *entry, McContentRegistryFlag flag){
    return entry != NULL && flag != MC_REGISTRY_FLAG_NONE && (entry->flags & (uint32_t)flag) == (uint32_t)flag;
}

static void validate_type_into(McContentRegistryType type, McContentRegistryValidation *validation){
    size_t start = first_index(type), count = compiled_count(type);
    validation->types++;
    validation->entries += count;
    for(size_t i = 0; i < count; i++){
        const McContentEntry *entry = &registry_entries[start + i];
        if(entry->id != i) validation->missing_ids++;
        if(entry->legacy_id >= 0) validation->legacy_mappings++;
        for(size_t j = 0; j < i; j++){
            if(registry_entries[start + j].id == entry->id) validation->duplicate_ids++;
            if(strcmp(registry_entries[start + j].name, entry->name) == 0) validation->duplicate_names++;
        }
    }
}

McStatus mc_content_registry_validate_type(McContentRegistryType type, McContentRegistryValidation *validation){
    if(validation == NULL || !valid_type(type)) return MC_INVALID_ARGUMENT;
    *validation = (McContentRegistryValidation){.ordered = true};
    validate_type_into(type, validation);
    validation->valid = validation->duplicate_ids == 0 && validation->duplicate_names == 0 && validation->missing_ids == 0;
    if(!validation->valid) validation->ordered = false;
    return validation->valid ? MC_OK : MC_FORMAT_ERROR;
}

McStatus mc_content_registry_validate(McContentRegistryValidation *validation){
    if(validation == NULL) return MC_INVALID_ARGUMENT;
    *validation = (McContentRegistryValidation){.ordered = true};
    for(int type = MC_REGISTRY_ITEM; type < MC_REGISTRY_TYPE_COUNT; type++){
        validate_type_into((McContentRegistryType)type, validation);
    }
    validation->valid = validation->duplicate_ids == 0 && validation->duplicate_names == 0 && validation->missing_ids == 0 && validation->entries == MC_CONTENT_REGISTRY_TOTAL_COUNT;
    if(!validation->valid) validation->ordered = false;
    return validation->valid ? MC_OK : MC_FORMAT_ERROR;
}

uint64_t mc_content_registry_hash(void){
    uint64_t hash = UINT64_C(1469598103934665603);
    for(size_t i = 0; i < MC_CONTENT_REGISTRY_TOTAL_COUNT; i++){
        const McContentEntry *entry = &registry_entries[i];
        const unsigned char *name = (const unsigned char *)entry->name;
        for(size_t j = 0; name[j] != 0; j++){ hash ^= name[j]; hash *= UINT64_C(1099511628211); }
        hash ^= entry->type; hash *= UINT64_C(1099511628211);
        hash ^= entry->id; hash *= UINT64_C(1099511628211);
        hash ^= entry->flags; hash *= UINT64_C(1099511628211);
    }
    return hash;
}

static McStatus write_u16_string(McBuffer *output, const char *value){
    size_t length = value == NULL ? 0 : strlen(value);
    if(length > UINT16_MAX) return MC_CAPACITY_EXCEEDED;
    McStatus status = mc_buffer_write_u16_be(output, (uint16_t)length);
    if(status == MC_OK) status = mc_buffer_write_bytes(output, value, length);
    return status;
}

static McStatus read_u16_string(McBuffer *input, char **value){
    uint16_t length = 0;
    McStatus status = mc_buffer_read_u16_be(input, &length);
    if(status != MC_OK || length > input->size - input->position) return MC_FORMAT_ERROR;
    char *copy = calloc((size_t)length + 1, 1);
    if(copy == NULL) return MC_OUT_OF_MEMORY;
    status = mc_buffer_read_bytes(input, copy, length);
    if(status != MC_OK){ free(copy); return status; }
    *value = copy;
    return MC_OK;
}

McStatus mc_content_registry_write_manifest(McBuffer *output){
    if(output == NULL) return MC_INVALID_ARGUMENT;
    mc_buffer_clear(output);
    McStatus status = mc_buffer_write_bytes(output, (uint8_t[]){MC_REGISTRY_MAGIC_0, MC_REGISTRY_MAGIC_1, MC_REGISTRY_MAGIC_2, MC_REGISTRY_MAGIC_3}, 4);
    if(status == MC_OK) status = mc_buffer_write_u16_be(output, MC_CONTENT_REGISTRY_VERSION);
    if(status == MC_OK) status = mc_buffer_write_u32_be(output, MC_CONTENT_REGISTRY_TOTAL_COUNT);
    for(size_t i = 0; status == MC_OK && i < MC_CONTENT_REGISTRY_TOTAL_COUNT; i++){
        const McContentEntry *entry = &registry_entries[i];
        status = mc_buffer_write_u8(output, (uint8_t)entry->type);
        if(status == MC_OK) status = mc_buffer_write_u16_be(output, entry->id);
        if(status == MC_OK) status = mc_buffer_write_u16_be(output, (uint16_t)entry->legacy_id);
        if(status == MC_OK) status = write_u16_string(output, entry->name);
        if(status == MC_OK) status = write_u16_string(output, entry->java_field);
        if(status == MC_OK) status = write_u16_string(output, entry->java_class);
        if(status == MC_OK) status = mc_buffer_write_u32_be(output, entry->flags);
    }
    return status;
}

McStatus mc_content_registry_read_manifest(const uint8_t *data, size_t size, McContentRegistryValidation *validation){
    if(data == NULL || validation == NULL || size < 10) return MC_INVALID_ARGUMENT;
    McBuffer input = {.data = (uint8_t *)data, .size = size, .capacity = size, .position = 0};
    uint8_t magic[4] = {0}; uint16_t version = 0; uint32_t count = 0;
    McStatus status = mc_buffer_read_bytes(&input, magic, 4);
    if(status == MC_OK && (magic[0] != MC_REGISTRY_MAGIC_0 || magic[1] != MC_REGISTRY_MAGIC_1 || magic[2] != MC_REGISTRY_MAGIC_2 || magic[3] != MC_REGISTRY_MAGIC_3)) status = MC_FORMAT_ERROR;
    if(status == MC_OK) status = mc_buffer_read_u16_be(&input, &version);
    if(status == MC_OK) status = mc_buffer_read_u32_be(&input, &count);
    *validation = (McContentRegistryValidation){.entries = count, .ordered = true};
    if(status != MC_OK || version != MC_CONTENT_REGISTRY_VERSION || count != MC_CONTENT_REGISTRY_TOTAL_COUNT) return MC_FORMAT_ERROR;
    for(uint32_t i = 0; status == MC_OK && i < count; i++){
        uint8_t type = 0; uint16_t id = 0; uint16_t legacy_bits = 0; uint32_t flags = 0;
        char *name = NULL; char *field = NULL; char *class_name = NULL;
        status = mc_buffer_read_u8(&input, &type);
        if(status == MC_OK) status = mc_buffer_read_u16_be(&input, &id);
        if(status == MC_OK) status = mc_buffer_read_u16_be(&input, &legacy_bits);
        if(status == MC_OK) status = read_u16_string(&input, &name);
        if(status == MC_OK) status = read_u16_string(&input, &field);
        if(status == MC_OK) status = read_u16_string(&input, &class_name);
        if(status == MC_OK) status = mc_buffer_read_u32_be(&input, &flags);
        if(status == MC_OK){
            const McContentEntry *entry = mc_content_registry_find((McContentRegistryType)type, name);
            if(entry == NULL || entry->id != id || entry->legacy_id != (int16_t)legacy_bits ||
               strcmp(entry->java_field, field) != 0 || strcmp(entry->java_class, class_name) != 0 ||
               entry->flags != flags) validation->missing_ids++;
        }
        free(name); free(field); free(class_name);
    }
    if(status == MC_OK && input.position != input.size) status = MC_FORMAT_ERROR;
    validation->valid = status == MC_OK && validation->missing_ids == 0;
    return validation->valid ? MC_OK : MC_FORMAT_ERROR;
}
